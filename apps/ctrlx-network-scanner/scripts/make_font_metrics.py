#!/usr/bin/env python3
"""Generate src/app/fontmetrics.py: character widths of the PDF standard fonts Helvetica and
Helvetica-Bold for the WinAnsi (cp1252) characters, measured from Liberation Sans.

    python3 scripts/make_font_metrics.py [/usr/share/fonts/truetype/liberation]

Liberation Sans is metric-compatible with Arial/Helvetica (same advance widths), and its files are
on Ubuntu (package fonts-liberation, SIL Open Font License). Only the numbers end up in the app,
no font data: the PDF uses the viewer's built-in Helvetica.
"""

import os
import struct
import sys


def read_ttf_widths(path):
    with open(path, "rb") as f:
        data = f.read()
    num_tables = struct.unpack_from(">H", data, 4)[0]
    tables = {}
    for i in range(num_tables):
        tag, _checksum, offset, length = struct.unpack_from(">4sIII", data, 12 + 16 * i)
        tables[tag.decode("latin-1")] = (offset, length)
    units = struct.unpack_from(">H", data, tables["head"][0] + 18)[0]
    n_hmetrics = struct.unpack_from(">H", data, tables["hhea"][0] + 34)[0]
    hmtx = tables["hmtx"][0]
    advances = [struct.unpack_from(">H", data, hmtx + 4 * i)[0] for i in range(n_hmetrics)]

    cmap = tables["cmap"][0]
    n_sub = struct.unpack_from(">H", data, cmap + 2)[0]
    sub = None
    for i in range(n_sub):
        platform, encoding, offset = struct.unpack_from(">HHI", data, cmap + 4 + 8 * i)
        if platform == 3 and encoding == 1:
            sub = cmap + offset
    if sub is None or struct.unpack_from(">H", data, sub)[0] != 4:
        raise SystemExit("no Windows Unicode BMP cmap (format 4) in " + path)
    seg_x2 = struct.unpack_from(">H", data, sub + 6)[0]
    segs = seg_x2 // 2
    ends = struct.unpack_from(">%dH" % segs, data, sub + 14)
    starts = struct.unpack_from(">%dH" % segs, data, sub + 16 + seg_x2)
    deltas = struct.unpack_from(">%dh" % segs, data, sub + 16 + 2 * seg_x2)
    range_off_at = sub + 16 + 3 * seg_x2
    range_offs = struct.unpack_from(">%dH" % segs, data, range_off_at)

    def glyph(cp):
        for i in range(segs):
            if starts[i] <= cp <= ends[i]:
                if range_offs[i] == 0:
                    return (cp + deltas[i]) & 0xFFFF
                addr = range_off_at + 2 * i + range_offs[i] + 2 * (cp - starts[i])
                g = struct.unpack_from(">H", data, addr)[0]
                return (g + deltas[i]) & 0xFFFF if g else 0
        return 0

    def width(cp):
        g = glyph(cp)
        adv = advances[g] if g < len(advances) else advances[-1]
        return round(adv * 1000 / units)

    result = []
    for code in range(32, 256):
        try:
            ch = bytes([code]).decode("cp1252")
        except UnicodeDecodeError:
            result.append(0)
            continue
        result.append(width(ord(ch)))
    return result


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/liberation"
    regular = read_ttf_widths(os.path.join(src, "LiberationSans-Regular.ttf"))
    bold = read_ttf_widths(os.path.join(src, "LiberationSans-Bold.ttf"))
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = os.path.join(here, "src", "app", "fontmetrics.py")

    def fmt(values):
        lines = []
        for i in range(0, len(values), 16):
            lines.append("    " + ", ".join(str(v) for v in values[i:i + 16]) + ",")
        return "\n".join(lines)

    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Advance widths (1/1000 em) of Helvetica / Helvetica-Bold for cp1252 codes 32..255.\n\n'
                "Generated by scripts/make_font_metrics.py from Liberation Sans (metric-compatible).\n"
                'Do not edit by hand."""\n\n')
        f.write("FIRST_CHAR = 32\n\n")
        f.write("HELVETICA = [\n" + fmt(regular) + "\n]\n\n")
        f.write("HELVETICA_BOLD = [\n" + fmt(bold) + "\n]\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
